export function getLang() {
  try {
    const l = window.localStorage.getItem(KEY);
    if (l && DICT[l]) return l;
  } catch {
    // sin almacenamiento
  }
  return "es";
}

export function setLang(l) {
  try {
    if (DICT[l]) window.localStorage.setItem(KEY, l);
  } catch {
    // sin almacenamiento
  }
  window.location.reload();
}

export function t(key, vars) {
  const lang = typeof window === "undefined" ? "es" : getLang();
  let s = DICT[lang]?.[key] ?? DICT.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

export function locale() {
  const lang = typeof window === "undefined" ? "es" : getLang();
  return lang === "en" ? "en-GB" : lang === "ar" ? "ar" : "es-ES";
}

export function isRTL() {
  return typeof window !== "undefined" && getLang() === "ar";
}

// Ajusta <html lang/dir> en el navegador (llamar desde un useEffect)
export function applyLangToDocument() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}
